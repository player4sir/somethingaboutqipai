function parseBuffer(buf, len) {
    if (len < 15) return;
    for (let i = 0; i < len - 14; i++) {
        if (buf.add(i + 4).readU8() === 0x51 && buf.add(i + 5).readU8() === 0x45) {
            const cmd = buf.add(i + 8).readS32();
            const cmdBig = ((cmd & 0xff) << 24) | ((cmd & 0xff00) << 8) | ((cmd >> 8) & 0xff00) | ((cmd >> 24) & 0xff);
            const cmdName = CMD_DICT[cmdBig] || ("Cmd_" + cmdBig);
            console.log(`[★ 麻将数据包] 偏移: ${i}, Cmd: ${cmdBig} (${cmdName})`);
            break;
        }
    }
}

